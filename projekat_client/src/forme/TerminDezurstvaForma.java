    private void btnDodajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajActionPerformed
        try {
            if (cmbDanUNedelji.getSelectedIndex() == -1) {
                throw new Exception("Morate izabrati dan u nedelji.");
            }
            if (cmbSmena.getSelectedIndex() == -1) {
                throw new Exception("Morate izabrati smenu.");
            }
            String danUNedelji = (String) cmbDanUNedelji.getSelectedItem();
            String smena = (String) cmbSmena.getSelectedItem();

            TerminDezurstva td = new TerminDezurstva(0, danUNedelji, smena);
            ClientController.getInstanca().dodajTerminDezurstva(td);
            JOptionPane.showMessageDialog(rootPane, "Систем је запамтио термин дежурства.");
            this.dispose();

        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, "Систем не може да запамти термин дежурства.");
            }

        }
    }//GEN-LAST:event_btnDodajActionPerformed

