    public void popuniTabeluEvidencija(boolean prikaziPoruku) {
        try {
            String kriterijum = txtPretraga.getText().trim();
            List<EvidencijaZaduzenja> list;

            if (rbtnEvidencija.isSelected()) {
                list = ClientController.getInstanca().pretraziEvidencijePoEvidenciji(kriterijum);
            } else if (rbtnBibliotekar.isSelected()) {
                list = ClientController.getInstanca().pretraziEvidencijePoBibliotekaru(kriterijum);
            } else if (rbtnClan.isSelected()) {
                list = ClientController.getInstanca().pretraziEvidencijePoClanu(kriterijum);
            } else {
                list = ClientController.getInstanca().pretraziEvidencijePoKnjizi(kriterijum);
            }

            if (list == null || list.isEmpty()) {
                JOptionPane.showMessageDialog(rootPane, "Систем не може да нађе евиденције задужења по задатим критеријумима.");

                tblEvidencije.setModel(new TableModelEvidencije(new ArrayList<>()));
                tblStavke.setModel(new TableModelStavke(new ArrayList<>()));
                return;
            }

            if (prikaziPoruku) {
                JOptionPane.showMessageDialog(rootPane, "Систем је нашао евидеције задужења по задатим критеријума");
            }

            tableModelEvidencije = new TableModelEvidencije(list);
            tblEvidencije.setModel(tableModelEvidencije);

            tableModelStavke = new TableModelStavke(new ArrayList<>());
            tblStavke.setModel(tableModelStavke);
        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, "Систем не може да нађе евиденције задужења по задатим критеријумима.");
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }

