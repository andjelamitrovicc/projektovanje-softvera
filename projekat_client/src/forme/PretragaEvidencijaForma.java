    private void btnObrisiEvidencijuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiEvidencijuActionPerformed
        try {
            int red = tblEvidencije.getSelectedRow();
            if (red > -1) {
                EvidencijaZaduzenja evidencijaZaduzenja = tableModelEvidencije.vratiNaIzabranomRedu(red);
                int opcija = JOptionPane.showConfirmDialog(rootPane, "Da li ste sigurni da zelite da obrisete?");
                if (opcija == JOptionPane.YES_OPTION) {
                    ClientController.getInstanca().obrisiEvidenciju(evidencijaZaduzenja);
                    JOptionPane.showMessageDialog(rootPane, "Систем је обрисао евиденцију задужења.");
                    popuniTabeluEvidencija(true);
                }
            }
        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, "Систем не може да обрише евиденцију задужења.");
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnObrisiEvidencijuActionPerformed

    private void tblEvidencijeMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblEvidencijeMouseClicked
        try {
            int red = tblEvidencije.getSelectedRow();
            if (red > -1) {
                EvidencijaZaduzenja evidencijaZaduzenja = tableModelEvidencije.vratiNaIzabranomRedu(red);
                EvidencijaZaduzenja ucitanaEvidencija = ClientController.getInstanca().ucitajEvidenciju(evidencijaZaduzenja);
                tableModelStavke = new TableModelStavke(ucitanaEvidencija.getStavkeZaduzenja());
                tblStavke.setModel(tableModelStavke);
                JOptionPane.showMessageDialog(rootPane, "Систем је нашао евиденцију задужења.");
            }
        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, "Систем не може да нађе евиденцију задужења.");
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }//GEN-LAST:event_tblEvidencijeMouseClicked

