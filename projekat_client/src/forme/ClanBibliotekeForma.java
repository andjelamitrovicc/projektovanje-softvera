    private void btnSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajActionPerformed
        try {
            String ime = txtIme.getText().trim();
            String prezime = txtPrezime.getText().trim();
            String telefon = txtTelefon.getText().trim();
            String datumTekst = txtDatumUclanjenja.getText();
            Odeljenje odeljenje = (Odeljenje) cmbOdeljenje.getSelectedItem();

            if (ime.isEmpty()) {
                throw new Exception("Morate uneti ime clana biblioteke.");
            }

            if (prezime.isEmpty()) {
                throw new Exception("Morate uneti prezime clana biblioteke.");
            }

            if (telefon.isEmpty()) {
                throw new Exception("Morate uneti broj telefona.");
            }

            if (datumTekst.isEmpty()) {
                throw new Exception("Morate uneti datum uclanjenja.");
            }

            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
            Date datumUclanjenja = sdf.parse(datumTekst);

            if (datumUclanjenja.after(new Date())) {
                throw new Exception("Datum uclanjenja ne moze biti iz buducnosti.");
            }

            if (clanBiblioteke.getIdClan() != 0) {
                clanBiblioteke.setImeClan(ime);
                clanBiblioteke.setPrezimeClan(prezime);
                clanBiblioteke.setTelefon(telefon);
                clanBiblioteke.setDatumUclanjenja(datumUclanjenja);
                clanBiblioteke.setOdeljenje(odeljenje);

                ClientController.getInstanca().izmeniClanaBiblioteke(clanBiblioteke);
                JOptionPane.showMessageDialog(rootPane, "Систем је запамтио члана библиотеке.");
            } else {
                ClanBiblioteke noviClanBiblioteke = new ClanBiblioteke(0, ime, prezime, telefon, datumUclanjenja, odeljenje);
                ClientController.getInstanca().sacuvajClanaBiblioteke(noviClanBiblioteke);
                JOptionPane.showMessageDialog(rootPane, "Систем је запамтио члана библиотеке.");
            }
        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, "Систем не може да запамти члана библиотеке.");
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnSacuvajActionPerformed

