    public ClanBibliotekeForma(ClanBiblioteke clanBiblioteke) {
        initComponents();
        setLocationRelativeTo(null);
        setDefaultCloseOperation(DISPOSE_ON_CLOSE);
        this.clanBiblioteke = clanBiblioteke;

        try {
            List<Odeljenje> listaOdeljenja = ClientController.getInstanca().pretraziOdeljenje("");
            cmbOdeljenje.removeAllItems();
            for (Odeljenje o : listaOdeljenja) {
                cmbOdeljenje.addItem(o);
            }

            if (clanBiblioteke.getIdClan() != 0) {
                txtIme.setText(clanBiblioteke.getImeClan());
                txtIme.setEnabled(false);
                txtPrezime.setText(clanBiblioteke.getPrezimeClan());
                txtPrezime.setEnabled(false);
                txtTelefon.setText(clanBiblioteke.getTelefon());

                SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
                txtDatumUclanjenja.setText(sdf.format(clanBiblioteke.getDatumUclanjenja()));
                txtDatumUclanjenja.setEnabled(false);

                cmbOdeljenje.setSelectedItem(clanBiblioteke.getOdeljenje());
                btnSacuvaj.setText("Izmeni");
            }
        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }

