    private void tblClanoviMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblClanoviMouseClicked
        try {
            int red = tblClanovi.getSelectedRow();
            if (red > -1) {
                ClanBiblioteke clanBiblioteke = tableModelClanovi.vratiNaIzabranomRedu(red);
                ClanBiblioteke ucitaniClan = ClientController.getInstanca().ucitajClana(clanBiblioteke);

                List<ClanBiblioteke> pomocnaLista = new ArrayList<>();
                pomocnaLista.add(ucitaniClan);

                tableModelClanovi = new TableModelClanovi(pomocnaLista);
                tblClanovi.setModel(tableModelClanovi);

                if (tblClanovi.getRowCount() > 0) {
                    tblClanovi.setRowSelectionInterval(0, 0);
                }

                JOptionPane.showMessageDialog(rootPane, "Систем је нашао члана библиотеке.");
            }
        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, "Систем не може да нађе члана библиотеке.");
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }//GEN-LAST:event_tblClanoviMouseClicked

