    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed
        try {
            int red = tblClanovi.getSelectedRow();
            if (red > -1) {
                ClanBiblioteke clanBiblioteke = tableModelClanovi.vratiNaIzabranomRedu(red);
                ClanBiblioteke ucitaniClan = ClientController.getInstanca().ucitajClana(clanBiblioteke);
                this.dispose();
                new ClanBibliotekeForma(ucitaniClan).setVisible(true);
            }
        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnIzmeniActionPerformed

    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed
        try {
            int red = tblClanovi.getSelectedRow();
            if (red > -1) {
                ClanBiblioteke clanBiblioteke = tableModelClanovi.vratiNaIzabranomRedu(red);
                int opcija = JOptionPane.showConfirmDialog(rootPane, "Da li ste sigurni da zelite da obrisete?");
                if (opcija == JOptionPane.YES_OPTION) {
                    ClientController.getInstanca().obrisiClanaBiblioteke(clanBiblioteke);
                    JOptionPane.showMessageDialog(rootPane, "Систем је обрисао члана библиотеке.");
                    popuniTabelu(true);
                }
            }

        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } 
            else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, "Систем не може да обрише члана библиотеке.");
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnObrisiActionPerformed

