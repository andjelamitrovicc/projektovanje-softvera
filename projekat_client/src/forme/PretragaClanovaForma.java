    public void popuniTabelu(boolean prikaziPoruku) {
        try {
            String kriterijum = txtPretraga.getText().trim();
            List<ClanBiblioteke> lista;

            if (rbtnClan.isSelected()) {
                lista = ClientController.getInstanca().pretraziClanovePoClanu(kriterijum);
            } else {
                lista = ClientController.getInstanca().pretraziClanovePoOdeljenju(kriterijum);
            }

            if (lista == null || lista.isEmpty()) {
                JOptionPane.showMessageDialog(rootPane, "Систем не може да нађе чланове библиотеке по задатим критеријумима.");

                tblClanovi.setModel(new TableModelClanovi(new ArrayList<>()));
                return;
            }

            if (prikaziPoruku) {
                JOptionPane.showMessageDialog(rootPane, "Систем је нашао чланове библиотеке по задатим критеријумима.");
            }

            tableModelClanovi = new TableModelClanovi(lista);
            tblClanovi.setModel(tableModelClanovi);

        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }

