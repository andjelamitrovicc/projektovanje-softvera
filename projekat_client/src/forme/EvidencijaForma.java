    private void btnSacuvajEvidencijuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajEvidencijuActionPerformed
        try {
            String status = (String) cmbStatus.getSelectedItem();
            ClanBiblioteke clanBiblioteke = (ClanBiblioteke) cmbClan.getSelectedItem();

            List<StavkaZaduzenja> stavke = tableModelStavke.getLista();

            if (stavke.isEmpty()) {
                throw new Exception("Morate uneti barem jednu stavku");
            }

            evidencijaZaduzenja.setStatus(status);
            evidencijaZaduzenja.setClan(clanBiblioteke);
            evidencijaZaduzenja.setStavkeZaduzenja(stavke);
            
            if (evidencijaZaduzenja.getIdZaduzenje() != 0) {
                ClientController.getInstanca().izmeniEvidenciju(evidencijaZaduzenja);
                JOptionPane.showMessageDialog(rootPane, "Систем је запамтио евиденцију задужења.");
            } else {
                ClientController.getInstanca().sacuvajEvidenciju(evidencijaZaduzenja);
                JOptionPane.showMessageDialog(rootPane, "Систем је запамтио евиденцију задужења.");
            }
            this.dispose();
        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, "Систем не може да запамти евиденцију задужења.");
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnSacuvajEvidencijuActionPerformed

