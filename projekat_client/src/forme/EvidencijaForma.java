    private void btnDodajStavkuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajStavkuActionPerformed
        try {
            ClanBiblioteke clanBiblioteke = (ClanBiblioteke)cmbClan.getSelectedItem();
            
            String datumOdTekst = txtDatumOd.getText();
            String datumDoTekst = txtDatumDo.getText();
            String kolicnaTekst = txtKolicina.getText();
            String napomena = txtNapomena.getText();
            Knjiga knjiga = (Knjiga) cmbKnjiga.getSelectedItem();

            if (datumOdTekst.isEmpty()) {
                throw new Exception("Niste uneli datum od");
            }

            if (datumDoTekst.isEmpty()) {
                throw new Exception("Niste uneli datum do");
            }

            if (kolicnaTekst.isEmpty()) {
                throw new Exception("Niste uneli kolicinu");
            }

            if (napomena.isEmpty()) {
                throw new Exception("Niste uneli napomenu");
            }

            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
            Date datumOd = sdf.parse(datumOdTekst);
            Date datumDo = sdf.parse(datumDoTekst);
            int kolicina = Integer.parseInt(kolicnaTekst);

            if (datumOd.after(new Date())) {
                throw new Exception("Datum od mora biti sad ili u proslosti");
            }

            if (datumDo.before(new Date())) {
                throw new Exception("Datum do mora biti u buducnosti");
            }

            if (kolicina <= 0) {
                throw new Exception("Kolicina mora biti veca od 0");
            }
            
            if(datumOd.before(clanBiblioteke.getDatumUclanjenja())){
                throw new Exception("Datum od je pre datuma uclanjenja clana");
            }

            StavkaZaduzenja stavka = new StavkaZaduzenja(evidencijaZaduzenja, 0, datumOd, datumDo, kolicina, napomena, knjiga);

            tableModelStavke.dodajStavku(stavka);
        } catch (Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnDodajStavkuActionPerformed

