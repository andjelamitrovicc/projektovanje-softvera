    private void btnPrijaviSeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrijaviSeActionPerformed
        try{
            String korisnickoIme = txtKorisnickoIme.getText().trim();
            String lozinka = String.valueOf(txtLozinka.getPassword());
            
            if(korisnickoIme.isEmpty()) {
                throw new Exception("Niste uneli korisnicko ime");
            }
            
            if(lozinka.isEmpty()) {
                throw new Exception("Niste uneli lozinku");
            }
            
            Bibliotekar bibliotekar = new Bibliotekar(0, null, null, korisnickoIme, lozinka);
            Bibliotekar ulogovani = ClientController.getInstanca().login(bibliotekar);
            ClientController.getInstanca().setUlogovani(ulogovani);
            JOptionPane.showMessageDialog(rootPane, "Корисничко име и шифра су исправни");
            this.dispose();
            new MainForm(ulogovani).setVisible(true);
        }catch(Exception ex) {
            if (ex instanceof SocketException) {
                JOptionPane.showMessageDialog(rootPane, "Server vam je prekinuo komunikaciju");
                System.exit(0);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(rootPane, "Корисничко име и шифра нису исправни");
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnPrijaviSeActionPerformed

