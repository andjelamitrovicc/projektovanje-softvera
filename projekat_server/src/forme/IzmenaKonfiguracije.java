    private void btnSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajActionPerformed
        try{
            File file = new File("konfiguracija.properties");
            FileOutputStream fileOutputStream = new FileOutputStream(file);
            Properties properties = new Properties();
            
            String url = txtUrl.getText().trim();
            String port = txtPort.getText().trim();
            String nazivBaze = txtNazivBaze.getText().trim();
            String usernameBaze = txtUsername.getText().trim();
            String passwordBaze = new String(txtPassword.getPassword());
            
            if(url.isEmpty()){
                throw new Exception("Niste uneli URL baze");
            }
            
            if(port.isEmpty()){
                throw new Exception("Niste uneli port baze");
            }
            
            if(nazivBaze.isEmpty()){
                throw new Exception("Niste uneli naziv baze");
            }
            
            if(usernameBaze.isEmpty()){
                throw new Exception("Niste uneli username baze");
            }
            
            properties.setProperty("url", url);
            properties.setProperty("port", port);
            properties.setProperty("nazivBaze", nazivBaze);
            properties.setProperty("usernameBaze", usernameBaze);
            properties.setProperty("passwordBaze", passwordBaze);
            
            properties.store(fileOutputStream, "");
            fileOutputStream.flush();
            fileOutputStream.close();
            
            JOptionPane.showMessageDialog(rootPane, "Uspesno ste izmenili konfiguraciju");
            this.dispose();
        }catch(Exception ex){
            ex.printStackTrace();
            JOptionPane.showMessageDialog(rootPane, ex.getMessage());
        }
    }//GEN-LAST:event_btnSacuvajActionPerformed

    
