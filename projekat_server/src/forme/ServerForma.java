    private void btnPokreniServerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPokreniServerActionPerformed
        try{
            String maxBrojKlijenataString = txtMaxBrojKlijenata.getText().trim();
            
            if(maxBrojKlijenataString.isEmpty()) {
                throw new Exception("Niste uneli maksimalan broj klijenata");
            }
            
            int maxBrojKlijenata = Integer.parseInt(maxBrojKlijenataString);
            
            if(maxBrojKlijenata <= 0) {
                throw new Exception("Maksimalan broj klijenata mora biti pozitivan broj.");
            }
            
            serverThread = new ServerThread(maxBrojKlijenata);
            serverThread.start();
            btnPokreniServer.setEnabled(false);
            btnUgasiServer.setEnabled(true);
        }catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(rootPane, ex.getMessage());
        }
    }//GEN-LAST:event_btnPokreniServerActionPerformed

